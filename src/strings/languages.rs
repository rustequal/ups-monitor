#[cfg(test)]
mod tests {
    use super::*;
    use crate::strings::{Key, KEYS, KEY_COUNT};

    /// English is the first entry, because the list is shown in this order and
    /// English is the one language every reader of it can fall back to.
    #[test]
    fn english_comes_first() {
        assert_eq!(LANGUAGES[0].code, "en");
    }

    #[test]
    fn language_codes_are_unique() {
        for (i, a) in LANGUAGES.iter().enumerate() {
            for b in &LANGUAGES[i + 1..] {
                assert_ne!(a.code, b.code, "duplicate language code {}", a.code);
            }
        }
    }

    /// The three spellings of a key say the same thing.
    ///
    /// `declare_keys!` takes each key as a variant, a field name and a dotted
    /// name on one line, and nothing in the macro relates them: a line reading
    /// `PanelInputVoltage panel_output_voltage "panel.input_voltage"` compiles,
    /// and a translator filling `panel_output_voltage` would be filling the
    /// input row. The `Debug` name of a variant is exactly the identifier, so
    /// comparing it against the dotted name checks two of the three columns
    /// against each other for all hundred and forty-one keys at once.
    ///
    /// The field name cannot be reached at runtime and is not checked here.
    /// It does not need to be: it is only ever a name, and the position it maps
    /// to is generated from the same line as the variant, so a wrong field name
    /// misleads a reader but cannot move a string.
    #[test]
    fn a_key_variant_and_its_dotted_name_agree() {
        for key in Key::ALL {
            let expected: String = key
                .label()
                .split(['.', '_'])
                .map(|part| {
                    let mut cs = part.chars();
                    match cs.next() {
                        Some(first) => first.to_uppercase().collect::<String>() + cs.as_str(),
                        None => String::new(),
                    }
                })
                .collect();
            assert_eq!(
                format!("{key:?}"),
                expected,
                "{} is spelled differently as a variant and as a name",
                key.label()
            );
        }
    }

    #[test]
    fn keys_are_unique() {
        for (i, a) in KEYS.iter().enumerate() {
            for b in &KEYS[i + 1..] {
                assert_ne!(a, b, "duplicate key {a}");
            }
        }
    }

    /// No language ships a blank string. The array length is checked by the
    /// compiler; emptiness is not, and an empty label draws as nothing at all
    /// rather than as an obvious mistake.
    #[test]
    fn no_translation_is_empty() {
        for l in &LANGUAGES {
            for (i, s) in l.strings.iter().enumerate() {
                assert!(!s.is_empty(), "{}: {} is empty", l.code, KEYS[i]);
            }
        }
    }

    /// The application name is the same in every language.
    ///
    /// It is a proper noun and the string Task Manager shows; a translated
    /// window caption over an untranslated executable name reads as two
    /// different programs. Pinned because the Russian table shipped a
    /// translated product name here before the rule existed.
    #[test]
    fn the_product_name_is_never_translated() {
        for key in [Key::PanelTitle, Key::InstanceAlreadyRunningTitle] {
            let i = key as usize;
            for l in &LANGUAGES {
                assert_eq!(
                    l.strings[i],
                    "UPS Monitor",
                    "{}: {} must stay the product name",
                    l.code,
                    key.label()
                );
            }
        }
    }

    /// The discriminant of a variant is its index, and every language fills
    /// every slot.
    ///
    /// `Key`'s discriminant is used directly as the index into `KEYS` and into
    /// every language's array, and `Key::ALL` must list the variants in that
    /// same order. That used to be the one thing standing between three
    /// hand-written lists and a silent mismatch, where every key would still
    /// resolve — just to the neighbouring string. The three lists are now
    /// generated from one table by `declare_keys!`, so they cannot disagree by
    /// construction; what remains worth pinning is the assumption underneath
    /// the whole scheme, that `#[repr(usize)]` numbers the variants from zero
    /// in declaration order. Dropping the explicit `= 0` … `= 140` made that
    /// assumption load-bearing rather than merely true.
    #[test]
    fn key_discriminants_match_their_tables() {
        assert_eq!(KEYS.len(), KEY_COUNT);
        assert_eq!(Key::ALL.len(), KEY_COUNT);
        for (i, key) in Key::ALL.iter().enumerate() {
            assert_eq!(
                *key as usize,
                i,
                "Key::ALL[{i}] = {} has discriminant {}, not {i}",
                key.label(),
                *key as usize
            );
        }
        // Every language supplies exactly one string per key slot.
        for l in &LANGUAGES {
            assert_eq!(
                l.strings.len(),
                KEY_COUNT,
                "{} has the wrong number of strings",
                l.code
            );
        }
    }

    /// A placeholder in English means a placeholder in every language: the
    /// substituted value is a number the sentence is about, and a translation
    /// that drops `{}` silently loses it.
    #[test]
    fn placeholders_survive_translation() {
        for (i, en) in LANGUAGES[0].strings.iter().enumerate() {
            if !en.contains("{}") {
                continue;
            }
            for l in &LANGUAGES {
                assert!(
                    l.strings[i].contains("{}"),
                    "{}: {} lost its placeholder",
                    l.code,
                    KEYS[i]
                );
            }
        }
    }

    /// No translation outgrows the space the layout gives it.
    ///
    /// Widths are counted in characters, not pixels, which is an
    /// approximation — but a sound one here, because the font of every
    /// language is fixed at compile time and the proportional widths of the
    /// scripts involved are close enough that a character budget with headroom
    /// catches what matters. CJK glyphs are counted double, being about twice
    /// the advance width of Latin at the same size.
    ///
    /// The budgets are the English width doubled and rounded up, the layout
    /// being required to hold strings twice as long as their English
    /// originals. A failure here is not automatically a bad translation: it
    /// may equally mean the theme's `panel_width` or `settings_width` needs
    /// raising. What it is never is something to discover from a screenshot.
    #[test]
    fn no_translation_exceeds_its_budget() {
        // (key prefix, budget in Latin-equivalent characters)
        const BUDGETS: [(&str, usize); 6] = [
            // Panel labels size their own column, so the ceiling is generous;
            // it exists to catch a translation that would push the value
            // column off the right edge entirely.
            ("panel.", 30),
            // Event checkboxes are the widest thing in the settings dialog.
            ("settings.on_", 40),
            ("settings.", 30),
            ("state.", 24),
            ("flag.", 40),
            ("test.", 28),
        ];
        for l in &LANGUAGES {
            let double_width = matches!(l.code, "zh" | "ja" | "ko");
            for (i, key) in KEYS.iter().enumerate() {
                // The product name is fixed and the same everywhere, and the
                // interval error is `Row::Wrapped` — it flows onto as many
                // lines as it needs, so a width budget does not apply to it.
                if matches!(*key, "panel.title" | "settings.invalid_interval") {
                    continue;
                }
                let Some((_, budget)) = BUDGETS.iter().find(|(p, _)| key.starts_with(p)) else {
                    continue;
                };
                let text = l.strings[i];
                let width: usize = text
                    .chars()
                    .map(|c| {
                        if double_width && c as u32 > 0x2E80 {
                            2
                        } else {
                            1
                        }
                    })
                    .sum();
                assert!(
                    width <= *budget,
                    "{}: {key} is {width} wide, budget {budget}: {text:?}",
                    l.code
                );
            }
        }
    }

    /// The widest entry in the language list fits the settings dialog.
    ///
    /// `English name (Native name)` is materially wider than either half, and
    /// the list is drawn inside the value column. Pinned separately from the
    /// string budgets because the failure is a different one: the fix is the
    /// theme's `settings_width`, not the translation.
    #[test]
    fn every_language_entry_fits_the_list() {
        // Value column at the shipped 430px settings width, less the label
        // column and padding, in characters at 11.25pt Segoe UI (~7px
        // average). Recomputed after the font size was corrected: the
        // previous figure assumed 9pt and was therefore too permissive by a
        // fifth, which is how a too-small font hid a too-narrow window.
        const BUDGET: usize = 30;
        for l in &LANGUAGES {
            let entry = if l.english_name == l.native_name {
                l.english_name.len()
            } else {
                // Native names in CJK are short but double width.
                let native: usize = l
                    .native_name
                    .chars()
                    .map(|c| if c as u32 > 0x2E80 { 2 } else { 1 })
                    .sum();
                l.english_name.chars().count() + native + 3
            };
            assert!(
                entry <= BUDGET,
                "{}: list entry is {entry} wide, budget {BUDGET}",
                l.code
            );
        }
    }

    /// Latin, Cyrillic and Greek need no font beyond Segoe UI; anything else
    /// names one. Guards against a language being added with a native name the
    /// default font cannot draw and no font declared to draw it.
    ///
    /// The boundary is U+0370, the end of Greek — not the start of the CJK
    /// blocks. Devanagari lives at U+0900, well below CJK, so a CJK-shaped
    /// threshold passed Hindi as needing nothing and would have shipped it
    /// drawn in a font without a single glyph for it.
    #[test]
    fn a_language_needing_a_font_declares_one() {
        // Segoe UI covers Latin, Latin Extended, Greek and Cyrillic, i.e.
        // everything below the Armenian block at U+0530.
        const COVERED_BY_SEGOE_UI: u32 = 0x0530;
        for l in &LANGUAGES {
            let needs = l
                .native_name
                .chars()
                .any(|c| c as u32 >= COVERED_BY_SEGOE_UI);
            assert_eq!(
                needs,
                l.font.is_some(),
                "{}: native name and declared font disagree",
                l.code
            );
        }
    }
}
