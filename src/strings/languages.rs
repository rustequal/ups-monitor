//! The translations themselves: one row per shipped language.
//!
//! Nothing here is read top to bottom. It is a data table — twenty-four
//! languages by [`super::KEY_COUNT`] strings — kept in its own file
//! so that editing it does not bury the schema in
//! [`keys`](super::keys), and so that adding a language shows up as a diff
//! against a data file rather than against the module every other part of the
//! program imports.
//!
//! The order of each `strings` array is the order of
//! [`Key`](super::Key)'s discriminants, and that is load-bearing: a lookup is
//! an index, not a search. The trailing `// key.name` comment on each line is
//! what makes that order checkable by eye; the tests below check it by
//! machine.

use super::{Strings, KEY_COUNT, LANGUAGE_COUNT};

/// One shipped language.
pub(crate) struct Language {
    /// INI value and internal identifier: `ru`, `zh`.
    pub code: &'static str,
    /// Shown first in the language list, always in Latin script so the
    /// entry is legible whether or not the native script can be drawn.
    pub english_name: &'static str,
    /// Shown in parentheses after `english_name`, omitted when the two are
    /// the same string.
    pub native_name: &'static str,
    /// Font used to draw `native_name` and the parts of this language's
    /// interface that Segoe UI cannot. `None` means Segoe UI, which covers
    /// Latin, Cyrillic and Greek. `Some` names one of the CJK/Devanagari UI
    /// fonts (Microsoft YaHei UI, Yu Gothic UI, Malgun Gothic, Nirmala UI),
    /// which are system fonts present on every installable desktop/server
    /// Windows edition and cannot be uninstalled.
    pub font: Option<&'static str>,
    pub strings: [&'static str; KEY_COUNT],
}

